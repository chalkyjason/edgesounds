"""Army Jay OSD icons -- every index that is not a letter, digit,
punctuation mark or boot-splash tile.

Covers 0x01-0x1F, 0x20 (space), the 16 home arrows at 0x60-0x6F,
and 0x70-0x9F. 0x00 and 0xFF are protected and come from stock, so
they are deliberately absent here.

Pictograms were sketched white-only and outlined by
``tools/outline_art.py``; text labels are composed from a bold 5x9
and a 3x5 bitmap font. Three-character labels are 1px strokes
because 12px of cell width allows nothing else -- the stock font
makes the same compromise in the same places.
"""

