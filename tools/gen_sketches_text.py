HEADER = '''"""{doc}

Generated by ``tools/outline_art.py`` from white-only sketches, then
committed as the outlined art that actually ships. Edit the art directly;
``validate.py`` check 10 keeps every white pixel's black surround intact.

Geometry: {geom}
"""

from __future__ import annotations

'''


def emit(path, doc, geom, entries):
    """entries: list of (key_repr, comment, art)"""
    body = [HEADER.format(doc=doc, geom=geom)]
    body.append(f"{entries['name']}: dict[int, str] = {{\n")
    for index, comment, art in entries["items"]:
        body.append(f"    # 0x{index:02X}  {comment}\n")
        body.append(f'    0x{index:02X}: """\n{art}\n""",\n')
    body.append("}\n")
    path.write_text("".join(body), encoding="utf-8", newline="\n")
    print(f"wrote {path} ({len(entries['items'])} glyphs)")


def main():
    # Letters occupy rows 3..14 so there is a clear margin top and bottom.
    letters = [
        (0x41 + i, f"letter {ch}", sketch_to_art(art, origin_y=3))
        for i, (ch, art) in enumerate(sorted(LETTERS.items()))
    ]
    emit(
        OUT / "letters.py",
        "Army Jay OSD letters -- A-Z at 0x41-0x5A.",
        "8 x 12 white form at rows 3-14, 2px strokes, 1px black outline.",
        {"name": "LETTERS", "items": letters},
    )

    numbers = [
        (0x30 + d, f"digit {d}", sketch_to_art(art, origin_y=3))
        for d, art in sorted(NUMBERS.items())
    ]
    emit(
        OUT / "numbers.py",
        "Army Jay OSD digits -- 0-9 at 0x30-0x39.\n\n"
        "Zero is slashed and one is flagged, so 0/O and 1/I stay distinct\n"
        "on a degraded analog feed.",
        "8 x 12 white form at rows 3-14, 2px strokes, 1px black outline.",
        {"name": "NUMBERS", "items": numbers},
    )

    punct = []
    for index, (name, art) in sorted(PUNCTUATION.items()):
        origin_y = 3 if index != 0x24 else 5
        punct.append((index, name, sketch_to_art(art, origin_y=origin_y)))
    emit(
        OUT / "punctuation.py",
        "Army Jay OSD punctuation and symbols.\n\n"
        "Covers 0x21-0x2F, 0x3A-0x40 and 0x5B-0x5F. 0x20 (space) is blank\n"
        "and lives in icons.py with the other structural blanks.",
        "8 x 12 white form at rows 3-14, 2px strokes, 1px black outline.",
        {"name": "PUNCTUATION", "items": punct},
    )


if __name__ == "__main__":
    main()
